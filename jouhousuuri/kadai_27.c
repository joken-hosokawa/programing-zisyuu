//課題27
#include <stdio.h>
int main()
{
	int gyou, i, j;

	scanf( "%d", &gyou );

	for( i = 1; i <= gyou; i++ ) {
		for( j = 1; j <= gyou; j++ ) {
			if( i == j || i + j == gyou + 1 ) //i=jまたは、i+jがgyou+1のとき
				printf( "■" );
			else
				printf( "□" );
		}
		printf( "\n" );
	}
	return 0;
}

/*
5
■□□□■
□■□■□
□□■□□
□■□■□
■□□□■

解説:
i==jの条件は、左上から左下の線を出力する。この場合、1行目では1列目、2行目は2列目となるので行と列の数字が同じときに出力すればよい。
i+j==gyou+1の条件は右上から左下の線を出力する。この場合出力する列が段々減っていく必要があるため、i+jがgyou+1(変化しない数)と等しくなるときに出力すればよい。
上記の2つをまたはで記述するとこで、2本の線が重なり×印になる。
*/
